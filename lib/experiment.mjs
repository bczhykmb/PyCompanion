export function makePrompt(group) {
  const item = GROUPS[group];
  if (!item) throw new Error('Invalid group');
  const roleStyle = ROLE_PROMPTS[['A', 'B'].includes(group) ? 'job' : 'peer'];
  return [COMMON_TEACHING_PROMPT, item.identity, roleStyle, FEEDBACK_PROMPTS[item.feedback === '积极反馈' ? 'positive' : 'neutral']].join('\n\n');
}
