export function makePrompt(group) {
  const item = GROUPS[group];
  if (!item) throw new Error('Invalid group');
  const roleStyle = ROLE_PROMPTS[['A', 'B'].includes(group) ? 'job' : 'peer'];
  return [COMMON_TEACHING_PROMPT, item.identity, roleStyle, FEEDBACK_PROMPTS[item.feedback === '积极反馈' ? 'positive' : 'neutral']].join('\n\n');
}
export function demoAnswer(group, question, code, task) {
  const prefix = {
    A: '可以按以下顺序检查。我以工程师导师的角色梳理步骤。',
    B: '你可以逐步尝试，不必一次解决所有问题。我以工程师导师的角色协助你梳理步骤。',
    C: '可以按以下顺序检查。我以同学伙伴的角色和你梳理步骤。',
    D: '你可以逐步尝试，不必一次解决所有问题。我以同学伙伴的角色陪你一起梳理步骤。',
  }[group];
  let answer;
  if (task === 'while-loop') {
    answer = '先检查结束标记是否会被当成一批数量。假如第一个输入就是 -1，程序应该进入循环吗？先沿着你现在的条件推演一次。';
  } else if (task === 'for-loop') {
    answer = '先关注总数变量在每轮循环后的变化。第一批和第二批分别读入后，它应当保存哪几批的数量？先用纸笔记录，再检查你的更新位置。';
  } else if (task === 'intro') {
    answer = '先观察给出的第一行示例，区分括号内的内容和外面的语法。下一行需要输出的是文字还是数字？先写一行并运行，看看是否符合任务要求。';
  } else if (/循环|for |while |range|遍历/.test(question + code) || task === 'loops') {
    answer = '先挑列表中的一个值，判断它是否应当计入数量。你现在的程序在遇到这个值时，会进入哪一条分支？先跟踪这一轮的变量变化。';
  } else if (/条件|if |else|elif|判断/.test(question + code) || task === 'conditions') {
    answer = '先核对边界：任务说明10和20也属于合格。把10代入你当前的第一个条件，它会被分到哪一类？先找出判断与要求是否一致。';
  } else if (/变量|print|input|类型|赋值/.test(question + code) || task === 'variables') {
    answer = '先分清两个变量各自保存什么：数量和单件质量。假设有两件同样的零件，总质量与单件质量有什么关系？先用自己的话说明，再尝试写出计算。';
  } else {
    answer = '这是一条演示回复，尚未连接真实大模型。我暂时不能分析任意代码。你可以先明确输入、预期输出和实际现象，再定位到需要检查的代码行。';
  }
  return `${prefix}\n\n${answer}\n\n[演示模式：规则回复，未调用大模型，也未运行代码]`;
}
